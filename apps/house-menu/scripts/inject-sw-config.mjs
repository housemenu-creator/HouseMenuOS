/**
 * Injects Firebase config into firebase-messaging-sw.js from environment variables.
 *
 * Usage:
 *   node scripts/inject-sw-config.mjs
 *
 * Reads:
 *   process.env.VITE_FIREBASE_API_KEY
 *   process.env.VITE_FIREBASE_AUTH_DOMAIN
 *   process.env.VITE_FIREBASE_DATABASE_URL
 *   process.env.VITE_FIREBASE_PROJECT_ID
 *   process.env.VITE_FIREBASE_STORAGE_BUCKET
 *   process.env.VITE_FIREBASE_MESSAGING_SENDER_ID
 *   process.env.VITE_FIREBASE_APP_ID
 *
 * Writes:
 *   public/_firebaseConfig.js  (gitignored — generated at build time)
 *
 * Falls back to a default that works in dev only (blocked on non-secure context).
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const outPath = resolve(projectRoot, 'public/_firebaseConfig.js');

const required = [
  'VITE_FIREBASE_API_KEY',
  'VITE_FIREBASE_AUTH_DOMAIN',
  'VITE_FIREBASE_DATABASE_URL',
  'VITE_FIREBASE_PROJECT_ID',
  'VITE_FIREBASE_STORAGE_BUCKET',
  'VITE_FIREBASE_MESSAGING_SENDER_ID',
  'VITE_FIREBASE_APP_ID',
];

const missing = required.filter((k) => !process.env[k]);

if (missing.length > 0) {
  console.warn(
    `⚠️  Missing VITE_FIREBASE_* env vars: ${missing.join(', ')}\n` +
      `   Skipping SW config injection. Service worker will not be registered.\n` +
      `   Copy .env.example → .env and fill in your Firebase project values.`,
  );
  // Write an empty config so the SW doesn't crash
  writeFileSync(outPath, 'self.__FIREBASE_CONFIG__ = null;\n', 'utf-8');
  console.log(`→ Wrote placeholder to ${outPath}`);
  process.exit(0);
}

const config = {
  apiKey: process.env.VITE_FIREBASE_API_KEY,
  authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN,
  databaseURL: process.env.VITE_FIREBASE_DATABASE_URL,
  projectId: process.env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.VITE_FIREBASE_APP_ID,
};

const content = `// Generated by scripts/inject-sw-config.mjs — DO NOT EDIT
self.__FIREBASE_CONFIG__ = ${JSON.stringify(config, null, 2)};
`;

// Ensure public/ exists
const outDir = dirname(outPath);
if (!existsSync(outDir)) {
  mkdirSync(outDir, { recursive: true });
}

writeFileSync(outPath, content, 'utf-8');
console.log('✓ Injected Firebase config into public/_firebaseConfig.js');
